CREATE TABLE wger_sync_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status VARCHAR(20) NOT NULL, dry_run BOOLEAN NOT NULL, started_at TIMESTAMPTZ NOT NULL,
    finished_at TIMESTAMPTZ, pages INTEGER NOT NULL, created INTEGER NOT NULL,
    updated INTEGER NOT NULL, skipped INTEGER NOT NULL, failed INTEGER NOT NULL, message VARCHAR(500)
);
CREATE TABLE uma_careers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL, training_plan_id BIGINT NOT NULL REFERENCES training_plans(id),
    status VARCHAR(16) NOT NULL, active_slot INTEGER UNIQUE, total_weeks INTEGER NOT NULL,
    current_week INTEGER NOT NULL, current_weekday VARCHAR(12) NOT NULL,
    strength INTEGER NOT NULL, endurance INTEGER NOT NULL, agility INTEGER NOT NULL,
    technique INTEGER NOT NULL, discipline INTEGER NOT NULL, energy INTEGER NOT NULL,
    fatigue INTEGER NOT NULL, mood INTEGER NOT NULL, confidence INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
    completed_at TIMESTAMPTZ, version BIGINT NOT NULL
);
CREATE TABLE uma_career_turns (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    career_id BIGINT NOT NULL REFERENCES uma_careers(id), week_number INTEGER NOT NULL,
    weekday VARCHAR(12) NOT NULL, action_type VARCHAR(20) NOT NULL, status VARCHAR(16) NOT NULL,
    training_plan_day_id BIGINT REFERENCES training_plan_days(id), workout_session_id BIGINT UNIQUE,
    rest_activity_id BIGINT, action_title_snapshot VARCHAR(120) NOT NULL,
    activity_category_snapshot VARCHAR(80), activity_duration_minutes_snapshot INTEGER,
    result_text VARCHAR(1000) NOT NULL, strength_delta INTEGER NOT NULL,
    endurance_delta INTEGER NOT NULL, agility_delta INTEGER NOT NULL, technique_delta INTEGER NOT NULL,
    discipline_delta INTEGER NOT NULL, energy_delta INTEGER NOT NULL, fatigue_delta INTEGER NOT NULL,
    mood_delta INTEGER NOT NULL, confidence_delta INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL, completed_at TIMESTAMPTZ,
    CONSTRAINT uq_uma_career_turn UNIQUE(career_id, week_number, weekday)
);
CREATE INDEX idx_exercise_definition_filters ON exercise_definitions(archived, source, category, name);
CREATE INDEX idx_exercise_media_exercise ON exercise_media(exercise_definition_id, type, sort_order);
CREATE INDEX idx_session_status ON workout_sessions(status, started_at);
